def softmax_loss(x, y):
    """
    计算 Softmax 分类的损失和梯度。

    输入:
    - x: 输入数据，形状 (N, C)，其中 x[i, j] 是第 i 个输入在第 j 个类别的分数。
    - y: 标签向量，形状 (N,)，其中 y[i] 是 x[i] 的标签，且 0 <= y[i] < C

    返回一个元组:
    - loss: 标量损失
    - dx: 损失相对于 x 的梯度
    """
    loss, dx = None, None

    ###########################################################################
    # TODO: 复制你在作业 1 中的解决方案。                                      #
    ###########################################################################
    
    # 1. 计算 Softmax 概率
    # 为了数值稳定性，减去每行的最大值
    shifted_logits = x - np.max(x, axis=1, keepdims=True)
    exp_scores = np.exp(shifted_logits)
    probs = exp_scores / np.sum(exp_scores, axis=1, keepdims=True)
    
    # 2. 计算 Loss
    # 提取正确类别的概率
    N = x.shape[0]
    correct_logprobs = -np.log(probs[range(N), y])
    loss = np.sum(correct_logprobs) / N
    
    # 3. 计算梯度 dx
    dx = probs.copy()
    dx[range(N), y] -= 1
    dx /= N
    ###########################################################################
    #                             你的代码结束                                #
    ###########################################################################
    return loss, dx
