def affine_backward(dout, cache):
    """计算仿射（全连接）层的反向传播。

    输入：
    - dout: 上游导数，形状为 (N, M)
    - cache: 包含以下内容的元组：
      - x: 输入数据，形状为 (N, d_1, ... d_k)
      - w: 权重，形状为 (D, M)
      - b: 偏置，形状为 (M,)

    返回一个元组，包含：
    - dx: 相对于 x 的梯度，形状为 (N, d1, ..., d_k)
    - dw: 相对于 w 的梯度，形状为 (D, M)
    - db: 相对于 b 的梯度，形状为 (M,)
    """
    x, w, b = cache
    dx, dw, db = None, None, None
    ###########################################################################
    # TODO: 从作业 1 中复制你的解。                                     #
    ###########################################################################
    
    N = x.shape[0]
    # 将输入展平，这与前向传播中的操作对应
    x_reshaped = x.reshape(N, -1)  # 形状变为 (N, D)

    # 计算关于 x 的梯度 dx
    # dout (N, M) dot w.T (M, D) -> (N, D)
    dx = dout.dot(w.T) 
    # 将 dx 恢复为原始输入的形状 (N, d1, ..., dk)
    dx = dx.reshape(x.shape)

    # 计算关于 w 的梯度 dw
    # x_reshaped.T (D, N) dot dout (N, M) -> (D, M)
    dw = x_reshaped.T.dot(dout)

    # 计算关于 b 的梯度 db
    # 对 dout 在 batch 维度 (axis=0) 求和
    db = np.sum(dout, axis=0)

    return dx, dw, db


